import { createClient } from '@/utils/supabase/server';
import { cookies } from 'next/headers';
import { Navbar } from '@/components/navbar';
import { Database, CheckCircle2, AlertCircle, Layers } from 'lucide-react';

export default async function TodosPage() {
  const cookieStore = await cookies();
  const supabase = createClient(cookieStore);

  let todos: any[] | null = null;
  let errorMsg: string | null = null;

  try {
    const { data, error } = await supabase.from('todos').select();
    if (error) {
      errorMsg = error.message;
    } else {
      todos = data;
    }
  } catch (err: any) {
    errorMsg = err.message || 'Failed to query Supabase';
  }

  return (
    <div className="min-h-screen bg-gradient-to-br from-[#F0F6FF] via-[#F8FAFC] to-[#EFF6FF] text-[#0F172A] flex flex-col">
      <Navbar />

      <main className="max-w-4xl mx-auto w-full px-4 sm:px-6 py-10 flex-1 space-y-6">
        <div>
          <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-bold bg-blue-50 text-blue-700 border border-blue-200 mb-2">
            <Database className="w-3.5 h-3.5 text-blue-600" />
            <span>Supabase Database Connection</span>
          </div>
          <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight text-slate-900">
            Supabase Live Test &amp; Data Integration
          </h1>
          <p className="text-xs sm:text-sm text-slate-500 mt-1">
            Endpoint: <code className="font-mono text-blue-600 bg-blue-50 px-2 py-0.5 rounded">https://yzcftwndlhubrykziiri.supabase.co</code>
          </p>
        </div>

        {/* Status Card */}
        <div className="p-6 rounded-3xl bg-white/95 backdrop-blur-xl border border-blue-100 shadow-sm space-y-4">
          <div className="flex items-center justify-between pb-3 border-b border-blue-50">
            <span className="font-bold text-xs text-slate-700">Database Query: &apos;todos&apos; table</span>
            <span className="px-2.5 py-0.5 rounded-full text-[10px] font-bold font-mono bg-emerald-50 text-emerald-700 border border-emerald-200">
              SUPABASE SSR CONNECTED
            </span>
          </div>

          {errorMsg ? (
            <div className="p-4 rounded-2xl bg-amber-50 border border-amber-200 text-xs text-amber-800 space-y-1">
              <div className="flex items-center gap-2 font-bold">
                <AlertCircle className="w-4 h-4 text-amber-600 shrink-0" />
                <span>Notice from Supabase:</span>
              </div>
              <p className="font-mono text-[11px] pl-6 text-amber-700">{errorMsg}</p>
              <p className="text-[11px] pl-6 text-slate-500 mt-1">
                If the &apos;todos&apos; table hasn&apos;t been created yet in your Supabase dashboard, you can run <code className="bg-white px-1 py-0.5 rounded border font-mono">create table todos (id bigint generated by default as identity primary key, name text);</code> in the Supabase SQL editor.
              </p>
            </div>
          ) : (
            <div className="space-y-3">
              {todos && todos.length > 0 ? (
                <ul className="divide-y divide-blue-50">
                  {todos.map((todo) => (
                    <li key={todo.id} className="py-2.5 flex items-center gap-3 text-xs">
                      <CheckCircle2 className="w-4 h-4 text-emerald-600" />
                      <span className="font-semibold text-slate-800">{todo.name || todo.title || JSON.stringify(todo)}</span>
                    </li>
                  ))}
                </ul>
              ) : (
                <div className="p-6 text-center text-xs text-slate-500 bg-blue-50/30 rounded-2xl border border-blue-100">
                  Connection successful! No rows found in the &apos;todos&apos; table yet.
                </div>
              )}
            </div>
          )}
        </div>
      </main>
    </div>
  );
}
